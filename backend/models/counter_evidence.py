from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class ReviewVerdict(str, Enum):
    SUPPORTED = "SUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    PARTIALLY_SUPPORTED = "PARTIALLY_SUPPORTED"
    UNRESOLVED = "UNRESOLVED"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


class CounterEvidenceChallenge(BaseModel):
    """
    Structured challenge generated by the Independent Review Team.
    Evaluates original findings against contradictory evidence and alternative explanations.
    """
    challenge_id: str
    finding_id: str
    original_hypothesis: str
    supporting_evidence: List[str] = Field(default_factory=list)
    contradictory_evidence: List[str] = Field(default_factory=list)
    alternative_explanations: List[str] = Field(default_factory=list)
    calculation_verification: str  # Deterministic tie-out verification note
    missing_evidence: List[str] = Field(default_factory=list)
    reviewer_role: str
    reviewer_verdict: ReviewVerdict
    verdict_rationale: str
    requires_escalation: bool = False
    reviewer_notes: Optional[str] = None


class CounterEvidenceReport(BaseModel):
    """
    Aggregated report of independent counter-evidence reviews.
    """
    challenges: List[CounterEvidenceChallenge] = Field(default_factory=list)
    total_reviewed: int = 0
    total_contradicted: int = 0
    total_supported: int = 0
    total_unresolved: int = 0
    summary: str
